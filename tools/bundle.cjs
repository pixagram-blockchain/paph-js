/* tools/bundle.cjs — build dist/paph53.browser.js.
 *
 * The three sources are root-attaching UMDs with no dependencies, so the
 * browser build is a concatenation under a wrapper that shadows `module`,
 * `require` and `self`: every factory then takes its root branch and
 * attaches to a private namespace, which the wrapper re-exports as a UMD
 * of its own (window.PAPH53 in a browser, module.exports in Node — the
 * latter lets the conformance smoke run the bundle byte-for-byte against
 * the source build).
 *
 *     node tools/bundle.cjs
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));

const parts = ['src/assignment.cjs', 'src/wire.cjs', 'src/paph-js.cjs'];
const body = parts.map((p) => '/* ==== ' + p + ' ==== */\n' + read(p)).join('\n');

const out =
  '/* @pixagram/paph-js ' + pkg.version + ' — browser bundle (generated by tools/bundle.cjs; do not edit).\n' +
  ' * Attaches PAPH53 to the global object (window in a browser, globalThis in\n' +
  ' * Node) — the conformance smoke requires it for side effects and reads\n' +
  ' * globalThis.PAPH53 to diff the bundle byte-for-byte against the source\n' +
  ' * build.  .wire and .assignment carry the engines.\n' +
  ' * (c) Pixagram SA — MIT. */\n' +
  '(function (global) {\n' +
  "'use strict';\n" +
  'var NS = {};\n' +
  '/* shadowed on purpose: force every inner UMD onto its root branch, rooted at NS */\n' +
  'var module, require, self = NS;\n' +
  body + '\n' +
  'var api = {};\n' +
  'for (var k in NS.paphjs) if (k !== "_internal") api[k] = NS.paphjs[k];\n' +
  'api.hash = NS.paphWire.hash; api.parseT1 = NS.paphWire.parseT1; api.parseT2 = NS.paphWire.parseT2;\n' +
  'api.WIRE_VERSION = NS.paphWire.WIRE_VERSION; api.EXTRACTION_PROFILE = NS.paphWire.EXTRACTION_PROFILE;\n' +
  'api.extractionProfileId = NS.paphWire.extractionProfileId;\n' +
  'api.wire = NS.paphWire; api.assignment = NS.paphAssign; api.comparator = NS.paphjs;\n' +
  'global.PAPH53 = api;\n' +
  '}(typeof window !== "undefined" ? window : globalThis));\n';

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'paph53.browser.js'), out);
console.log('wrote dist/paph53.browser.js', out.length, 'bytes');
